"""Bundle model/{feature_spec.json, prepare.py, train.py or evaluate.py} into one Kaggle script kernel.

    python kaggle/bundle.py                              # full run, epochs planned from the time budget
    python kaggle/bundle.py --arch v4 --aug strong --epochs 160 --no-baseline --budget 600
    (the 65.5% model was --arch v2 --aug v2 with feature_spec v3, i.e. resample.length 32)
    python kaggle/bundle.py --entry evaluate          # model evaluation kernel -> kaggle/evaluate/
    python kaggle/bundle.py --entry reference         # reference animations for all signs -> kaggle/reference/
    python kaggle/bundle.py --smoke                      # 3000 sequences, 2 epochs, to catch bugs first

The kernel writes the files to /tmp/signseek_src and runs <entry>.main(), so Kaggle runs exactly the repo code.
"""

import argparse
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
COMMON = ["feature_spec.json", "prepare.py"]
# entry -> (extra files from model/, module whose main() runs)
ENTRIES = {
    "train": (["train.py"], "train"),
    "evaluate": (["evaluate.py"], "evaluate"),
    "reference": (["reference.py", "reference_export.py"], "reference_export"),
}
TEMPLATE = '''# Generated by kaggle/bundle.py from model/. Do not edit: edit model/ and re-bundle.
import os
import sys

FILES = {files}
SRC = "/tmp/signseek_src"
os.makedirs(SRC, exist_ok=True)
for name, text in FILES.items():
    with open(os.path.join(SRC, name), "w", encoding="utf-8") as fh:
        fh.write(text)
sys.path.insert(0, SRC)
os.environ["SIGNSEEK_SPEC"] = os.path.join(SRC, "feature_spec.json")
os.environ.update({env})

import {entry}  # noqa: E402

{entry}.main()
'''


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--entry", choices=list(ENTRIES), default="train",
                    help="train -> kaggle/train/, evaluate -> kaggle/evaluate/, reference -> kaggle/reference/")
    ap.add_argument("--smoke", action="store_true")
    ap.add_argument("--epochs", type=int, default=0, help="fixed epoch count (default: plan from time budget)")
    ap.add_argument("--no-baseline", action="store_true", help="skip the no-augmentation comparison model")
    ap.add_argument("--budget", type=float, default=55, help="kernel wall-clock budget, minutes")
    ap.add_argument("--arch", choices=["v2", "v4"], default="v4", help="v2 = the 65.5%% model; v4 = conv+transformer")
    ap.add_argument("--aug", choices=["v2", "strong"], default="strong", help="augmentation preset")
    args = ap.parse_args()
    env = {
        "SIGNSEEK_ARCH": args.arch,
        "SIGNSEEK_AUG": args.aug,
        "SIGNSEEK_SMOKE": "1" if args.smoke else "0",
        "SIGNSEEK_EPOCHS": str(args.epochs),
        "SIGNSEEK_BASELINE": "0" if args.no_baseline else "1",
        "SIGNSEEK_BUDGET_MIN": str(args.budget),
    }
    extra, module = ENTRIES[args.entry]
    files = {name: (REPO / "model" / name).read_text(encoding="utf-8") for name in COMMON + extra}
    out = REPO / "kaggle" / args.entry / f"signseek_{args.entry}.py"
    out.write_text(TEMPLATE.format(files=repr(files), env=repr(env), entry=module), encoding="utf-8")
    print("wrote", out.relative_to(REPO), env)


if __name__ == "__main__":
    main()
